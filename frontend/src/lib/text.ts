/** True if the text holds a control character or a Unicode line separator (a mail-header risk). */
export function hasControlOrLineBreak(text: string): boolean {
  for (const char of text) {
    const code = char.codePointAt(0) ?? 0;
    if (code <= 0x1f || code === 0x7f || code === 0x2028 || code === 0x2029) return true;
  }
  return false;
}
